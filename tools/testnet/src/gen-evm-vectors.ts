// Writes contracts/behest/src/testdata/evm-vectors.json: EIP-191 signed
// actions made with viem for the contract's D23 unit tests. Fixed keys and
// RFC 6979 signing make the output deterministic.
// Usage: pnpm --filter @behest/testnet exec tsx src/gen-evm-vectors.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { privateKeyToAccount } from "viem/accounts";
import { signedActionMessage, type SignedAction } from "@behest/relayer/evm";
import { ROOT } from "./near.js";

const C = "behest.testnet";
const DAY = 86_400_000;
const NOW = 1_000 * DAY; // the unit tests' clock
const DEADLINE = String(NOW + 10 * 60_000);
/** For vectors used after the tests advance the clock past an overdue plan and its waiting period. */
const LATER = String(NOW + 365 * DAY);

const keys = {
  a: privateKeyToAccount(`0x${"11".repeat(32)}`), // an EVM owner
  b: privateKeyToAccount(`0x${"22".repeat(32)}`), // an EVM guardian
  c: privateKeyToAccount(`0x${"33".repeat(32)}`), // an EVM heir
  d: privateKeyToAccount(`0x${"44".repeat(32)}`), // registered as an executor / admin in tests
};
const addr = (k: keyof typeof keys) => keys[k].address.toLowerCase();

const N = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;

/** Same signature, other s: (r, n − s, v ^ 1). Recovers the same key; must be refused. */
function highS(sig: string): string {
  const r = sig.slice(2, 66);
  const s = BigInt(`0x${sig.slice(66, 130)}`);
  const v = parseInt(sig.slice(130, 132), 16);
  return `0x${r}${(N - s).toString(16).padStart(64, "0")}${(v === 27 ? 28 : 27).toString(16)}`;
}

const planA = {
  check_in_interval_ms: 90 * DAY,
  grace_ms: 7 * DAY,
  waiting_period_ms: 30 * DAY,
  guardians: ["g1.testnet", "g2.testnet", "g3.testnet"],
  quorum: 2,
  heirs: [
    { account_id: "amara.testnet", share_bps: 6000, near_destination: "amara.testnet", eth_destination: null },
    { account_id: "tobi.testnet", share_bps: 4000, near_destination: "tobi-wallet.testnet", eth_destination: null },
  ],
};

interface Spec {
  name: string;
  key: keyof typeof keys;
  summary?: string;
  action: Partial<SignedAction> & { method: string };
  /** Replace the JSON body after building (for malformed cases). */
  tamper?: (message: string) => string;
}

const specs: Spec[] = [
  { name: "owner_set_plan", key: "a", summary: "Create your Behest plan", action: { method: "set_plan", args: { plan: planA } } },
  { name: "owner_check_in_1", key: "a", summary: "Check in", action: { method: "check_in", args: {}, nonce: "1", deadline_ms: LATER } },
  { name: "owner_check_in_0", key: "a", summary: "Check in", action: { method: "check_in", args: {} } },
  { name: "utf8_summary", key: "a", summary: "Check in — Kemi’s plan ✓", action: { method: "check_in", args: {} } },
  { name: "wrong_contract", key: "a", action: { method: "check_in", args: {}, contract: "other.testnet" } },
  { name: "wrong_network", key: "a", action: { method: "check_in", args: {}, network: "mainnet" } },
  { name: "wrong_actor", key: "a", action: { method: "check_in", args: {}, actor: addr("b") } },
  { name: "expired", key: "a", action: { method: "check_in", args: {}, deadline_ms: String(NOW - 1) } },
  { name: "wrong_nonce", key: "a", action: { method: "check_in", args: {}, nonce: "5" } },
  { name: "padded_nonce", key: "a", action: { method: "check_in", args: {}, nonce: "00" } },
  { name: "method_deposit", key: "a", action: { method: "deposit", args: { owner: "owner.testnet" } } },
  { name: "method_set_paused", key: "d", action: { method: "set_paused", args: { paused: true }, deadline_ms: LATER } },
  { name: "method_add_executor", key: "d", action: { method: "add_executor", args: { account_id: addr("d") } } },
  { name: "method_evm_call", key: "a", action: { method: "evm_call", args: { message: "x", signature: "0x" } } },
  { name: "unknown_arg", key: "a", action: { method: "check_in", args: { owner: "owner.testnet" }, nonce: "1" } },
  { name: "extra_field", key: "a", action: { method: "check_in", args: {} }, tamper: (m) => m.replace(/}$/, ',"extra":"1"}') },
  { name: "no_blank_line", key: "a", action: { method: "check_in", args: {} }, tamper: (m) => m.replace("\n\n", "\n") },
  { name: "guardian_propose", key: "b", summary: "Propose releasing owner.testnet's plan", action: { method: "propose_release", args: { owner: "owner.testnet" }, deadline_ms: LATER } },
  { name: "heir_claim", key: "c", summary: "Claim your share of owner.testnet's plan", action: { method: "claim", args: { owner: "owner.testnet" }, deadline_ms: LATER } },
  { name: "executor_cancel_withdrawal", key: "d", action: { method: "cancel_vault_withdrawal", args: { owner: "owner.testnet" }, deadline_ms: LATER } },
];

const out: Record<string, unknown> = {
  _note: "Generated by tools/testnet/src/gen-evm-vectors.ts (viem signMessage). Clock: block time 1000 days; deadline = +10 min, or +365 days for vectors used later in a test.",
  addresses: Object.fromEntries(Object.keys(keys).map((k) => [k, addr(k as keyof typeof keys)])),
  vectors: {},
};
for (const s of specs) {
  const action: SignedAction = {
    contract: C,
    network: "testnet",
    actor: addr(s.key),
    nonce: "0",
    deadline_ms: DEADLINE,
    args: {},
    ...s.action,
  };
  let message = signedActionMessage(s.summary ?? `Behest: ${s.action.method}`, action);
  if (s.tamper) message = s.tamper(message);
  const signature = await keys[s.key].signMessage({ message });
  (out.vectors as Record<string, unknown>)[s.name] = { message, signature };
  if (s.name === "owner_check_in_0") (out.vectors as Record<string, unknown>).high_s = { message, signature: highS(signature) };
}
const file = join(ROOT, "contracts/behest/src/testdata/evm-vectors.json");
writeFileSync(file, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${Object.keys(out.vectors as object).length} vectors to ${file}`);
