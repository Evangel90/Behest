use near_sdk::env;

/// Coded errors. The code before the colon is stable; the UI maps it to copy.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    Unauthorized,
    Paused,
    PlanExists,
    NoPlan,
    ProposalExists,
    NoProposal,
    NotOverdue,
    NotGuardian,
    NotHeir,
    AlreadyVoted,
    NotProposed,
    CancelWindowClosed,
    NotEligible,
    NothingToDistribute,
    InsufficientFeeReserve,
    InsufficientEscrow,
    InsufficientDeposit,
    InvalidHeirs,
    DuplicateHeir,
    InvalidShares,
    NoDestination,
    InvalidEthAddress,
    InvalidGuardians,
    InvalidQuorum,
    ConflictingRole,
    DurationOutOfBounds,
    ProposalOpen,
    InvalidTransferState,
    BadIndex,
    BadDestination,
    UnknownToken,
    VaultBusy,
    NoWithdrawal,
    BadAsset,
    InsufficientTokenEscrow,
    InvalidRules,
    NotReassignable,
    InvalidOptions,
    NotDelaySigner,
    ExtensionTooLong,
    ExtensionPending,
    NotReleasable,
    BtcVaultUnknown,
    InvalidBtcAddress,
    InvalidUtxos,
    BtcNotHead,
    FeeAtCap,
    NoLightClient,
    InvalidProof,
    RevertNotProven,
    EvmMessage,
    EvmSignature,
    EvmWrongContract,
    EvmActor,
    EvmNonce,
    EvmExpired,
    EvmMethod,
    EvmArgs,
    SponsorExhausted,
    InvalidTiers,
    InsufficientTreasury,
    NotDelegate,
    InvalidDelegates,
}

